%% Exterior-only stagnant-cap bubble: cap-angle and cone-family comparison
% Purpose: retain the 64-angle uniform-proxy speed sweep from phi=0 to pi,
% then compare cone S with cone S+T_t+T_n+T_n2 at five interior angles.
% Compare signed speed with Sadhal-Johnson bubble drag (53), including both
% endpoints. The uniform interior Stokeslet proxy remains fixed throughout.
%
% Edit: angleCount, comparisonTargets, baseOptions, coneInput, and the cone
% family and derivative selections below.
% Cone cases default to five source levels and ringLevels=10 per region.
% Added cone basis blocks raise collocation azimuths while retaining ring
% offsets. collocClusterRatio controls the exponential approach to the edge.
% Each solve prints actual counts and a dense SVD storage preflight.
%
% Checks: At comparison angles, all three cases use the same two shifted
% validation grids. Report four normalized boundary maxima and grid changes,
% matrix rank, force balance, transverse drift, and torque. Cone cases are
% inapplicable at endpoints; absent boundary conditions are NaN.
%
% Output: experiments/results/oct24_stagnant_cap_bubble_phi_sweep.csv,
% _families.csv, _speed.png, and _residuals.png. Existing files with those
% names are overwritten when this script is run.
% Run from the repository root: run('drops/experiments/oct24_stagnant_cap_bubble_phi_sweep.m')
clear; close all;
experimentDirectory = fileparts(mfilename('fullpath'));
repositoryDirectory = fileparts(fileparts(experimentDirectory));
addpath(fullfile(repositoryDirectory,'drops'), ...
    fullfile(repositoryDirectory,'images'), ...
    fullfile(repositoryDirectory,'common','dense'), ...
    fullfile(repositoryDirectory,'geometry','spheres'), ...
    fullfile(repositoryDirectory,'tools'));
outputDirectory = fullfile(experimentDirectory,'results');
if ~isfolder(outputDirectory), mkdir(outputDirectory); end

% Fixed physics, source proxy, truncation, and collocation policy.
angleCount = 64;
collocClusterRatio = 0.5; % 0<q<1; smaller q moves added rings closer to the edge.
baseOptions = bubble_options(struct('radius',1,'muOut',1, ...
    'innerProxyRatio',0.63,'sourceRequest',700, ...
    'collocationRatio',1.5,'svdTolerance',1e-12, ...
    'ringLevels',4,'useExtraCollocation',true, ...
    'collocClusterRatio',collocClusterRatio, ...
    'gravity',[0 0 -1],'densityDifference',1,'n_level',0));
comparisonTargets = [pi/8,pi/4,pi/2,3*pi/4,7*pi/8];
coneInput = struct('n_level',5,'ringLevels',10, ...
    'innerSourceStartDistance',0.35*baseOptions.radius, ...
    'sourceClusterRatio',0.7,'n_az_source',64, ...
    'n_az_colloc',80,'collocAngularExtent',0.2, ...
    'collocClusterRatio',collocClusterRatio, ...
    'use_orth_dir_images',false);
coneFamilySets = {"S",["S","T_t","T_n","T_n2"]};
coneDerivativeDirections = ["none","none"];
caseNames = strings(1,3);
caseNames(1) = "uniform S";
for c = 1:2
    caseNames(c+1) = "cone "+strjoin(coneFamilySets{c},'+');
    if coneDerivativeDirections(c)~="none"
        caseNames(c+1) = caseNames(c+1)+ ...
            "+S_y("+coneDerivativeDirections(c)+")";
    end
end
Fg = (4*pi*baseOptions.radius^3/3)* ...
    baseOptions.densityDifference*baseOptions.gravity(:);
assert(Fg(3)~=0);
phiRadians = linspace(0,pi,angleCount).';
phiDegrees = rad2deg(phiRadians);
comparisonIndices = zeros(numel(comparisonTargets),1);
for j = 1:numel(comparisonTargets)
    [~,comparisonIndices(j)] = min(abs(phiRadians-comparisonTargets(j)));
end
assert(numel(unique(comparisonIndices))==numel(comparisonTargets) && ...
    all(comparisonIndices>1 & comparisonIndices<angleCount), ...
    'Increase angleCount to resolve all five interior comparisons.');
comparisonIndices = sort(comparisonIndices);
comparisonRowCount = numel(comparisonIndices)+2;
comparisonUz = nan(comparisonRowCount,3);
comparisonSpeedError = nan(comparisonRowCount,3);
comparisonCollocation = nan(comparisonRowCount,3);
comparisonCoefficients = nan(comparisonRowCount,3);
comparisonRingLevels = nan(comparisonRowCount,3);
comparisonAzimuths = nan(comparisonRowCount,3);
comparisonRank = nan(comparisonRowCount,3);
comparisonKnownDenseGB = nan(comparisonRowCount,3);
comparisonValidationCount = nan(comparisonRowCount,3);
comparisonValidationEdgeDistanceOverA = nan(comparisonRowCount,3);
comparisonSourceDistanceOverA = nan(comparisonRowCount,3);
comparisonAddedRingDistanceOverA = nan(comparisonRowCount,3);
comparisonForceResidual = nan(comparisonRowCount,3);
comparisonTransverseDrift = nan(comparisonRowCount,3);
comparisonTorque = nan(comparisonRowCount,3);
comparisonUnresolved = nan(comparisonRowCount,3);
comparisonMaxima = nan(comparisonRowCount,3,4);
comparisonChanges = nan(comparisonRowCount,3,4);
comparisonApplicable = false(comparisonRowCount,3);
sourcePoints = zeros(angleCount,1);
ringLevels = zeros(angleCount,1);
collocationPoints = zeros(angleCount,1);
capPoints = zeros(angleCount,1);
mobilePoints = zeros(angleCount,1);
validationPoints = zeros(angleCount,1);
fineValidationPoints = zeros(angleCount,1);
minimumValidationEdgeDistanceOverA = nan(angleCount,1);
minimumCollocationEdgeDistanceOverA = nan(angleCount,1);
minimumAddedRingDistanceOverA = nan(angleCount,1);
svdRows = zeros(angleCount,1);
svdColumns = zeros(angleCount,1);
svdKnownDenseGB = zeros(angleCount,1);
retainedRank = zeros(angleCount,1);
numericalUz = zeros(angleCount,1);
theoreticalUz = zeros(angleCount,1);
relativeSpeedError = zeros(angleCount,1);
forceRelativeResidual = zeros(angleCount,1);
transverseDrift = zeros(angleCount,1);
normalizedTorque = zeros(angleCount,1);
boundaryMaxima = nan(angleCount,4);
validationChange = nan(angleCount,4);
validationUnresolved = false(angleCount,1);
fixedSources = [];

for k = 1:angleCount
    opt = baseOptions;
    opt.phi = phiRadians(k);
    opt.edgeBandAngle = [];
    opt.collocAngularExtent = [];
    opt = bubble_options(opt);
    geometry = bubble_geometry(opt);
    assert(geometry.coneSourceCount==0);
    if isempty(fixedSources)
        fixedSources = geometry.sourcePoints;
    else
        assert(isequal(geometry.sourcePoints,fixedSources), ...
            'The uniform proxy changed during the angle sweep.');
    end
    solution = bubble_solve(opt,Fg,geometry);
    drag = stagnant_cap_exact_drag(phiRadians(k),0, ...
        opt.muOut,opt.radius);
    selectedPosition = find(comparisonIndices==k,1);
    if isempty(selectedPosition)
        check = bubble_check_validation(solution,opt);
    else
        row = selectedPosition+1;
        coneOptions = cell(2,1);
        coneGrids = cell(2,1);
        coneFields = fieldnames(coneInput);
        for c = 1:2
            input = opt;
            for h = 1:numel(coneFields)
                input.(coneFields{h}) = coneInput.(coneFields{h});
            end
            input.refinementFamilies = coneFamilySets{c};
            input.derivative_direction = coneDerivativeDirections(c);
            coneOptions{c} = bubble_options(input);
            coneGrids{c} = bubble_geometry(coneOptions{c});
            assert(isequal(geometry.sourcePoints, ...
                coneGrids{c}.sourcePoints(1:geometry.sourceCount,:)), ...
                'The cone case changed the uniform proxy.');
        end
        assert(isequal(coneGrids{1}.sourcePoints, ...
            coneGrids{2}.sourcePoints) && ...
            isequal(coneGrids{1}.ringOffsets, ...
            coneGrids{2}.ringOffsets));
        if coneGrids{2}.coneFamilyCount>coneGrids{1}.coneFamilyCount
            assert(coneGrids{2}.collocationCount> ...
                coneGrids{1}.collocationCount);
        end
        maximumM = max([geometry.collocationCount, ...
            coneGrids{1}.collocationCount,coneGrids{2}.collocationCount]);
        finestOffset = coneGrids{1}.ringOffsets(end);
        if ~isempty(geometry.ringOffsets)
            finestOffset = min(finestOffset,geometry.ringOffsets(end));
        end
        sharedValidation = bubble_validation_grid( ...
            opt,maximumM,finestOffset);
        fineOptions = opt;
        fineOptions.validationBaseRequest = max( ...
            opt.validationBaseRequest,2*maximumM);
        fineOptions = bubble_options(fineOptions);
        fineOffset = min(finestOffset/2, ...
            sharedValidation.minimumEdgeDistance/opt.radius);
        sharedFine = bubble_validation_grid( ...
            fineOptions,2*maximumM,fineOffset);
        comparisonSolutions = cell(3,1);
        comparisonOptions = cell(3,1);
        comparisonGrids = cell(3,1);
        comparisonSolutions{1} = solution;
        comparisonOptions{1} = opt;
        comparisonGrids{1} = geometry;
        for c = 2:3
            comparisonOptions{c} = coneOptions{c-1};
            comparisonGrids{c} = coneGrids{c-1};
            fprintf('Comparison at %.3g deg: %s.\n', ...
                phiDegrees(k),caseNames(c));
            fprintf(['Nearest source %.5g a from interface; ', ...
                'added ring %.5g a from edge.\n'], ...
                comparisonGrids{c}.minimumSourceDistance/opt.radius, ...
                comparisonGrids{c}.minimumAddedEdgeDistance/opt.radius);
            comparisonSolutions{c} = bubble_solve( ...
                comparisonOptions{c},Fg,comparisonGrids{c});
        end
        for c = 1:3
            caseSolution = comparisonSolutions{c};
            caseGrid = comparisonGrids{c};
            caseCheck = bubble_check_validation( ...
                caseSolution,comparisonOptions{c}, ...
                sharedValidation,sharedFine);
            if c==1, check = caseCheck; end
            comparisonUz(row,c) = caseSolution.U(3);
            comparisonSpeedError(row,c) = abs( ...
                caseSolution.U(3)-Fg(3)/drag)/abs(Fg(3)/drag);
            comparisonCollocation(row,c) = caseGrid.collocationCount;
            comparisonCoefficients(row,c) = caseGrid.coefficientCount;
            comparisonRingLevels(row,c) = ...
                caseGrid.collocationRingCount(1);
            comparisonAzimuths(row,c) = caseGrid.ringAzimuthCount;
            comparisonRank(row,c) = caseSolution.retainedRank;
            comparisonKnownDenseGB(row,c) = ...
                caseSolution.svdKnownDenseMB/1000;
            comparisonValidationCount(row,c) = sharedValidation.count;
            comparisonValidationEdgeDistanceOverA(row,c) = ...
                sharedValidation.minimumEdgeDistance/opt.radius;
            comparisonSourceDistanceOverA(row,c) = ...
                caseGrid.minimumSourceDistance/opt.radius;
            comparisonAddedRingDistanceOverA(row,c) = ...
                caseGrid.minimumAddedEdgeDistance/opt.radius;
            comparisonForceResidual(row,c) = ...
                caseSolution.forceResidual;
            comparisonTransverseDrift(row,c) = ...
                caseSolution.transverseDrift;
            comparisonTorque(row,c) = norm(caseSolution.torque)/ ...
                (norm(Fg)*opt.radius);
            comparisonUnresolved(row,c) = caseCheck.unresolved;
            comparisonMaxima(row,c,:) = reshape( ...
                caseCheck.report.maxima,1,1,4);
            comparisonChanges(row,c,:) = reshape( ...
                caseCheck.relativeChange,1,1,4);
            comparisonApplicable(row,c) = true;
        end
    end
    theoreticalUz(k) = Fg(3)/drag;
    numericalUz(k) = solution.U(3);
    relativeSpeedError(k) = abs(numericalUz(k)-theoreticalUz(k))/ ...
        abs(theoreticalUz(k));
    sourcePoints(k) = geometry.sourceCount;
    ringLevels(k) = geometry.collocationRingCount(1);
    collocationPoints(k) = geometry.collocationCount;
    capPoints(k) = geometry.capCount;
    mobilePoints(k) = geometry.mobileCount;
    validationPoints(k) = check.validation.count;
    fineValidationPoints(k) = check.fineValidation.count;
    if phiRadians(k)>0 && phiRadians(k)<pi
        minimumValidationEdgeDistanceOverA(k) = ...
            check.validation.minimumEdgeDistance/opt.radius;
        minimumCollocationEdgeDistanceOverA(k) = ...
            geometry.minimumEdgeDistance/opt.radius;
        minimumAddedRingDistanceOverA(k) = ...
            geometry.minimumAddedEdgeDistance/opt.radius;
    end
    svdRows(k) = solution.matrixSize(1);
    svdColumns(k) = solution.matrixSize(2);
    svdKnownDenseGB(k) = solution.svdKnownDenseMB/1000;
    retainedRank(k) = solution.retainedRank;
    forceRelativeResidual(k) = solution.forceResidual;
    transverseDrift(k) = solution.transverseDrift;
    normalizedTorque(k) = norm(solution.torque)/(norm(Fg)*opt.radius);
    boundaryMaxima(k,:) = check.report.maxima;
    validationChange(k,:) = check.relativeChange;
    validationUnresolved(k) = check.unresolved;
    fprintf(['phi %6.1f deg: Uz %.6g, theory %.6g, relative error %.3g; ', ...
        'N=%d, M=%d, rank=%d; nearest added ring %.3g a.\n'], ...
        phiDegrees(k),numericalUz(k), ...
        theoreticalUz(k),relativeSpeedError(k),sourcePoints(k), ...
        collocationPoints(k),retainedRank(k), ...
        minimumAddedRingDistanceOverA(k));
end

% Endpoint cone cases have no cap edge or cone nodes and remain inapplicable.
for endpointRow = [1,comparisonRowCount]
    if endpointRow==1, angleIndex = 1; else, angleIndex = angleCount; end
    comparisonUz(endpointRow,1) = numericalUz(angleIndex);
    comparisonSpeedError(endpointRow,1) = ...
        relativeSpeedError(angleIndex);
    comparisonCollocation(endpointRow,1) = ...
        collocationPoints(angleIndex);
    comparisonCoefficients(endpointRow,1) = 3*sourcePoints(angleIndex);
    comparisonRingLevels(endpointRow,1) = ringLevels(angleIndex);
    comparisonAzimuths(endpointRow,1) = 0;
    comparisonRank(endpointRow,1) = retainedRank(angleIndex);
    comparisonKnownDenseGB(endpointRow,1) = ...
        svdKnownDenseGB(angleIndex);
    comparisonValidationCount(endpointRow,1) = ...
        validationPoints(angleIndex);
    comparisonSourceDistanceOverA(endpointRow,1) = ...
        1-baseOptions.innerProxyRatio;
    comparisonForceResidual(endpointRow,1) = ...
        forceRelativeResidual(angleIndex);
    comparisonTransverseDrift(endpointRow,1) = ...
        transverseDrift(angleIndex);
    comparisonTorque(endpointRow,1) = normalizedTorque(angleIndex);
    comparisonUnresolved(endpointRow,1) = ...
        validationUnresolved(angleIndex);
    comparisonMaxima(endpointRow,1,:) = reshape( ...
        boundaryMaxima(angleIndex,:),1,1,4);
    comparisonChanges(endpointRow,1,:) = reshape( ...
        validationChange(angleIndex,:),1,1,4);
    comparisonApplicable(endpointRow,1) = true;
end

assert(abs(stagnant_cap_exact_drag(0,0,baseOptions.muOut, ...
    baseOptions.radius)-4*pi*baseOptions.muOut*baseOptions.radius)<1e-12);
assert(abs(stagnant_cap_exact_drag(pi,0,baseOptions.muOut, ...
    baseOptions.radius)-6*pi*baseOptions.muOut*baseOptions.radius)<1e-12);
fprintf('Endpoint checks: clean bubble 4 pi mu a; stagnant sphere 6 pi mu a.\n');

results = table(phiRadians,phiDegrees,sourcePoints,ringLevels, ...
    collocationPoints, ...
    capPoints,mobilePoints,validationPoints,fineValidationPoints, ...
    minimumValidationEdgeDistanceOverA, ...
    minimumCollocationEdgeDistanceOverA,minimumAddedRingDistanceOverA, ...
    svdRows,svdColumns,svdKnownDenseGB,retainedRank, ...
    numericalUz,theoreticalUz,relativeSpeedError,forceRelativeResidual, ...
    transverseDrift,normalizedTorque,validationUnresolved, ...
    boundaryMaxima(:,1),boundaryMaxima(:,2),boundaryMaxima(:,3), ...
    boundaryMaxima(:,4),validationChange(:,1),validationChange(:,2), ...
    validationChange(:,3),validationChange(:,4), ...
    'VariableNames',{'phiRadians','phiDegrees','sourcePoints', ...
    'ringLevels','collocationPoints','capPoints','mobilePoints', ...
    'validationPoints', ...
    'fineValidationPoints','minimumValidationEdgeDistanceOverA', ...
    'minimumCollocationEdgeDistanceOverA','minimumAddedRingDistanceOverA', ...
    'svdRows','svdColumns','svdKnownDenseGB','retainedRank', ...
    'numericalUz','theoreticalUz', ...
    'relativeSpeedError','forceRelativeResidual','transverseDrift', ...
    'normalizedTorque','validationUnresolved','capNormalMax', ...
    'mobileNormalMax','capTangentMax','mobileTractionMax', ...
    'capNormalValidationChange','mobileNormalValidationChange', ...
    'capTangentValidationChange','mobileTractionValidationChange'});
writetable(results,fullfile(outputDirectory, ...
    'oct24_stagnant_cap_bubble_phi_sweep.csv'));

sampleIndices = [1;comparisonIndices;angleCount];
comparisonPhiRadians = repelem(phiRadians(sampleIndices),3);
comparisonPhiDegrees = repelem(phiDegrees(sampleIndices),3);
comparisonCase = repmat(caseNames(:),comparisonRowCount,1);
applicable = reshape(comparisonApplicable.',[],1);
comparisonTheoreticalUz = repelem(theoreticalUz(sampleIndices),3);
maximumRows = reshape(permute(comparisonMaxima,[2 1 3]),[],4);
changeRows = reshape(permute(comparisonChanges,[2 1 3]),[],4);
familyResults = table(comparisonPhiRadians,comparisonPhiDegrees, ...
    comparisonCase,applicable,comparisonTheoreticalUz, ...
    reshape(comparisonUz.',[],1), ...
    reshape(comparisonSpeedError.',[],1), ...
    reshape(comparisonCollocation.',[],1), ...
    reshape(comparisonCoefficients.',[],1), ...
    reshape(comparisonRingLevels.',[],1), ...
    reshape(comparisonAzimuths.',[],1), ...
    reshape(comparisonRank.',[],1), ...
    reshape(comparisonKnownDenseGB.',[],1), ...
    reshape(comparisonValidationCount.',[],1), ...
    reshape(comparisonValidationEdgeDistanceOverA.',[],1), ...
    reshape(comparisonSourceDistanceOverA.',[],1), ...
    reshape(comparisonAddedRingDistanceOverA.',[],1), ...
    reshape(comparisonForceResidual.',[],1), ...
    reshape(comparisonTransverseDrift.',[],1), ...
    reshape(comparisonTorque.',[],1), ...
    reshape(comparisonUnresolved.',[],1), ...
    'VariableNames',{'phiRadians','phiDegrees','caseName', ...
    'applicable','theoreticalUz','numericalUz','relativeSpeedError', ...
    'collocationCount','coefficientCount','ringLevels', ...
    'ringAzimuthCount','retainedRank','knownDenseGB', ...
    'validationCount','minimumValidationEdgeDistanceOverA', ...
    'minimumSourceDistanceOverA','minimumAddedRingDistanceOverA', ...
    'forceRelativeResidual','transverseDrift', ...
    'normalizedTorque','validationUnresolved'});
familyResults.capNormalMax = maximumRows(:,1);
familyResults.mobileNormalMax = maximumRows(:,2);
familyResults.capTangentMax = maximumRows(:,3);
familyResults.mobileTractionMax = maximumRows(:,4);
familyResults.capNormalValidationChange = changeRows(:,1);
familyResults.mobileNormalValidationChange = changeRows(:,2);
familyResults.capTangentValidationChange = changeRows(:,3);
familyResults.mobileTractionValidationChange = changeRows(:,4);
writetable(familyResults,fullfile(outputDirectory, ...
    'oct24_stagnant_cap_bubble_phi_sweep_families.csv'));

finePhi = linspace(0,pi,401);
fineTheory = Fg(3)./stagnant_cap_exact_drag( ...
    finePhi,0,baseOptions.muOut,baseOptions.radius);
speedFigure = figure('Name','Bubble speed versus cap angle','Color','w');
layout = tiledlayout(speedFigure,1,2,'TileSpacing','compact');
ax = nexttile(layout);
plot(ax,rad2deg(finePhi),fineTheory,'k-','LineWidth',1.5);
hold(ax,'on');
plot(ax,phiDegrees,numericalUz,'bo-','MarkerFaceColor','b');
selectedDegrees = phiDegrees(comparisonIndices);
plot(ax,selectedDegrees,comparisonUz(2:end-1,2),'r^-', ...
    'MarkerFaceColor','r');
plot(ax,selectedDegrees,comparisonUz(2:end-1,3),'ms-', ...
    'MarkerFaceColor','m');
xlabel(ax,'Cap angle (degrees)'); ylabel(ax,'Signed axial speed');
legend(ax,cellstr(["Sadhal-Johnson (53)",caseNames]), ...
    'Location','best'); grid(ax,'on');
ax = nexttile(layout);
semilogy(ax,phiDegrees,max(relativeSpeedError,eps),'ro-', ...
    'MarkerFaceColor','r');
hold(ax,'on');
semilogy(ax,selectedDegrees,max(comparisonSpeedError(2:end-1,2),eps), ...
    'b^-','MarkerFaceColor','b');
semilogy(ax,selectedDegrees,max(comparisonSpeedError(2:end-1,3),eps), ...
    'ms-','MarkerFaceColor','m');
xlabel(ax,'Cap angle (degrees)'); ylabel(ax,'Relative speed error');
legend(ax,cellstr(caseNames),'Location','best'); grid(ax,'on');
exportgraphics(speedFigure,fullfile(outputDirectory, ...
    'oct24_stagnant_cap_bubble_phi_sweep_speed.png'),'Resolution',180);

residualFigure = figure('Name','Bubble boundary maxima versus cap angle', ...
    'Color','w');
layout = tiledlayout(residualFigure,2,2,'TileSpacing','compact');
names = {'Cap normal velocity','Mobile normal velocity', ...
    'Cap tangential velocity','Mobile tangential traction'};
for j = 1:4
    ax = nexttile(layout,j);
    semilogy(ax,phiDegrees,max(boundaryMaxima(:,j),eps),'o-', ...
        'LineWidth',1.2);
    hold(ax,'on');
    semilogy(ax,selectedDegrees, ...
        max(comparisonMaxima(2:end-1,2,j),eps),'^-', ...
        'LineWidth',1.2);
    semilogy(ax,selectedDegrees, ...
        max(comparisonMaxima(2:end-1,3,j),eps),'s-', ...
        'LineWidth',1.2);
    xlabel(ax,'Cap angle (degrees)');
    ylabel(ax,'Maximum normalized residual');
    title(ax,names{j}); grid(ax,'on');
    legend(ax,cellstr(caseNames),'Location','best');
end
exportgraphics(residualFigure,fullfile(outputDirectory, ...

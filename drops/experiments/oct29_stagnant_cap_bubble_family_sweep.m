%% October 29: enhancing-source combinations on shared collocation points
% Snapshot of commonInput in oct24_stagnant_cap_bubble_residuals.m.
% The original experiment and its output files are preserved.
% Compare the four normalized physical boundary maxima and their maximum;
% speed error and fit residual alone do not establish boundary accuracy.
clear; close all;
experimentDirectory = fileparts(mfilename('fullpath'));
repositoryDirectory = fileparts(fileparts(experimentDirectory));
addpath(fullfile(repositoryDirectory,'drops'), ...
    fullfile(repositoryDirectory,'images'), ...
    fullfile(repositoryDirectory,'common','dense'), ...
    fullfile(repositoryDirectory,'geometry','spheres'), ...
    fullfile(repositoryDirectory,'tools'));

commonInput = struct('radius',1,'muOut',1,'phi',pi/4, ...
    'innerProxyRatio',0.63,'sourceRequest',700, ...
    'collocationRatio',2,'svdTolerance',1e-8, ...
    'useColumnScaling',false,'useAreaWeights',false, ...
    'gravity',[0 0 -1],'densityDifference',1, ...
    'n_level',5,'ringLevels',10,'innerSourceStartDistance',0.35, ...
    'useSourceRefinement',true,'sourceRefinementLevels',1, ...
    'sourceRefinementRadialFactors',[0.25 0.5 1 2], ...
    'sourceRefinementAzimuthFactors',[-2 -1 0 1 2], ...
    'sourceClustering',"tapered",'sourceClusterSigma',3, ...
    'sourceClusterRatio',0.1,'n_az_source',64, ...
    'n_az_colloc',80,'collocAngularExtent',0.5, ...
    'collocClustering',"geometric",'collocClusterSigma',6, ...
    'collocClusterRatio',0.5,'use_orth_dir_images',false);

% S Stokeslet; D potential dipole; R rotlet; Q_s axial Stokeslet quadrupole.
% T_t/T_n/T_n2 are the three oriented stresslet blocks. Legacy T is also
% supported, but cannot be combined with any T_* block in the same case.
% Every enhancing family adds three coefficients per fixed enhancing node.
familySets = {"S","SD","SR","ST_t","ST_n","ST_n2","SQ_s", ...
    "ST_tT_nT_n2","ST_tT_nT_n2R","SDRT_tT_nT_n2Q_s"};
% Optional derivative cases: append "S" to familySets and append "radial"
% or "cone_normal" to derivativeDirections; ordinary cases use "none".
derivativeDirections = repmat("none",numel(familySets),1);

% The densest individually affordable case supplies ONE shared fit grid.
% All solved cases retain exactly those targets and the same source sites.
% Two independent validation grids are shared too. Larger bases are marked
% budget_limit, never silently coarsened. Cases are solved sequentially.
% This 8 GB estimate is a planning cap, not an operating-system memory limit.
% Reduce it to suit available RAM; large combinations may then be skipped.
controls = struct('familySets',{familySets}, ...
    'derivativeDirections',derivativeDirections, ...
    'maxMemoryGB',8,'maxSvdRows',30000,'maxSvdColumns',10000, ...
    'maxCollocationPoints',10000,'planOnly',false,'makePlots',true, ...
    'figureVisible','on','outputDirectory', ...
    fullfile(experimentDirectory,'results','oct29_bubble_family_sweep'));
% planOnly=true prints matrix sizes/budgets without solving.
% To study scaling, rerun with useColumnScaling=true in commonInput and a
% DIFFERENT outputDirectory. The cutoff and flags are common to all cases.
% A lower fit residual can coexist with a higher independent maximum.
% Each validation-stable winner passes a 10% grid-change check; this is
% numerical evidence only, not a continuous-surface accuracy certificate.
result = bubble_family_sweep(commonInput,controls);


%% OCT24_STAGNANT_CAP_DERIVATIVES: compare source derivative directions.
% Run explicitly. All source and evaluation points are shared by both cases.
% Edit n_level for cone source rings and ringLevels for collocation rings
% on each side of the cap edge. collocAngularExtent and collocClusterRatio
% set their outer offset and exponential clustering.
experimentDirectory = fileparts(mfilename('fullpath'));
repositoryDirectory = fileparts(fileparts(experimentDirectory));
addpath(fullfile(repositoryDirectory,'drops'), ...
    fullfile(repositoryDirectory,'images'), ...
    fullfile(repositoryDirectory,'common','dense'), ...
    fullfile(repositoryDirectory,'common','eval'), ...
    fullfile(repositoryDirectory,'geometry','spheres'), ...
    fullfile(repositoryDirectory,'tools'));
outputDirectory = fullfile(experimentDirectory,'results');
if ~isfolder(outputDirectory), mkdir(outputDirectory); end

% Copy the Oct 23 physical and proxy parameters; use five enhancing levels.
opt = stagnant_cap_options(struct( ...
    'radius',1,'muOut',1,'muIn',2,'phi',pi/4, ...
    'innerProxyRatio',0.5,'outerProxyRatio',1.8, ...
    'sourceRequest',400,'collocationRatio',1.5, ...
    'svdTolerance',1e-12,'gravity',[0 0 -1], ...
    'densityDifference',1,'useExtraCollocation',false, ...
    'n_level',5,'ringLevels',20, ...
    'innerSourceStartDistance',0.35, ...
    'outerSourceStartDistance',0.45, ...
    'sourceClusterRatio',0.7,'n_az_source',64, ...
    'n_az_colloc',64,'collocAngularExtent',0.2, ...
    'collocClusterRatio',0.8,'refinementFamilies',"S", ...
    'derivative_direction',"radial"));
% Convert the requested per-region ring count for the shared cone builder.
familyCount = numel(opt.refinementFamilies)+ ...
    double(opt.derivative_direction~="none");
assert(opt.n_level>0 && familyCount>0 && ...
    opt.ringLevels>=2*opt.n_level*familyCount);
opt.colloc_factor = opt.ringLevels/(opt.n_level*familyCount);
directions = ["radial";"cone_normal"];
geometries = cell(2,1);
for k = 1:2
    caseOpt = opt;
    caseOpt.derivative_direction = directions(k);
    geometries{k} = stagnant_cap_refined_geometry(caseOpt);
end
reference = geometries{1};
other = geometries{2};
assert(isequal(reference.innerSources,other.innerSources) && ...
    isequal(reference.outerSources,other.outerSources) && ...
    isequal(reference.points,other.points) && ...
    isequal(reference.normals,other.normals) && ...
    isequal(reference.innerDerivativeDistances, ...
    other.innerDerivativeDistances) && ...
    isequal(reference.outerDerivativeDistances, ...
    other.outerDerivativeDistances));
assert(reference.enhancingFamilyCount==2 && ...
    isequal(reference.collocationRingCount, ...
        [opt.ringLevels opt.ringLevels]));
pointInside = size(reference.innerSources,1);
pointOutside = size(reference.outerSources,1);
unknowns = reference.exteriorCoefficientCount+ ...
    reference.interiorCoefficientCount;
matrixRows = 6*reference.collocationCount;
assert(reference.N==422 && ...
    isequal(reference.addedSourceCount,[320 320]) && ...
    pointInside==742 && pointOutside==742 && unknowns==6372 && ...
    reference.collocationCount==3209 && matrixRows==19254);
thinSize = min(matrixRows,unknowns);
matrixGB = 8*matrixRows*unknowns/1e9;
factorGB = 8*(matrixRows*thinSize+unknowns*thinSize+thinSize^2)/1e9;
fprintf(['Preflight: %d/%d distinct source points, %d enhancing families ', ...
    'and %d basis blocks per flow, %d scalar unknowns; matrix %d x %d.\n'], ...
    pointInside,pointOutside,reference.enhancingFamilyCount, ...
    numel(reference.exteriorBasis),unknowns,matrixRows,unknowns);
fprintf(['One matrix %.2f GB; known dense SVD storage >= %.2f GB ', ...
    'before workspace and assembly arrays.\n'], ...
    matrixGB,2*matrixGB+factorGB);

validation = stagnant_cap_validation_grid( ...
    opt,reference.collocationCount,reference.ringOffsets(end));
assert(validation.count>=5*reference.collocationCount && ...
    validation.minimumEdgeDistance<min(reference.edgeDistance));
fprintf(['Independent validation: %d points (%s base), ', ...
    'minimum edge distance %.8g a.\n'], ...
    validation.count,validation.baseMethod, ...
    validation.minimumEdgeDistance/opt.radius);
Fg = (4*pi*opt.radius^3/3)*opt.densityDifference*opt.gravity;
forceScale = norm(Fg);
exactSpeed = Fg(3)/stagnant_cap_exact_drag( ...
    opt.phi,opt.muIn,opt.muOut,opt.radius);
solutions = cell(2,1);
reports = cell(2,1);
summary = table(directions,'VariableNames',{'direction'});
summary.ringLevels = repmat(opt.ringLevels,2,1);
summaryNames = {'distinctSourcePointsInside','distinctSourcePointsOutside', ...
    'enhancingFamilyCount','basisBlocksPerFlow','scalarUnknowns', ...
    'collocationPoints','matrixRows','matrixColumns','retainedRank', ...
    'validationPoints','minimumEdgeDistanceOverA','speed', ...
    'theoreticalSpeed','speedRelativeError','forceRelativeError', ...
    'torqueRelativeMagnitude','capContinuityMax','mobileContinuityMax', ...
    'capNoPenetrationMax','mobileNoPenetrationMax', ...
    'capTangentialMax','mobileTractionMax', ...
    'enhancingStokesletMaxOverForce','derivativeMaxOverForce'};
for j = 1:numel(summaryNames)
    summary.(summaryNames{j}) = zeros(2,1);
end
regionRows = table();
for k = 1:2
    caseOpt = opt;
    caseOpt.derivative_direction = directions(k);
    solutions{k} = solve_stagnant_cap(caseOpt, ...
        struct('kind','force','Fg',Fg),geometries{k});
    reports{k} = stagnant_cap_validate( ...
        solutions{k},validation,caseOpt);
    rows = reports{k}.table;
    rows.direction = repmat(directions(k),height(rows),1);
    regionRows = [regionRows;rows]; 
    solution = solutions{k};
    report = reports{k};
    summary.distinctSourcePointsInside(k,1) = pointInside;
    summary.distinctSourcePointsOutside(k,1) = pointOutside;
    summary.enhancingFamilyCount(k,1) = reference.enhancingFamilyCount;
    summary.basisBlocksPerFlow(k,1) = numel(reference.exteriorBasis);
    summary.scalarUnknowns(k,1) = unknowns;
    summary.collocationPoints(k,1) = reference.collocationCount;
    summary.matrixRows(k,1) = solution.matrixSize(1);
    summary.matrixColumns(k,1) = solution.matrixSize(2);
    summary.retainedRank(k,1) = solution.retainedRank;
    summary.validationPoints(k,1) = validation.count;
    summary.minimumEdgeDistanceOverA(k,1) = ...
        validation.minimumEdgeDistance/opt.radius;
    summary.speed(k,1) = solution.U(3);
    summary.theoreticalSpeed(k,1) = exactSpeed;
    summary.speedRelativeError(k,1) = abs(solution.U(3)/exactSpeed-1);
    summary.forceRelativeError(k,1) = solution.forceResidual/forceScale;
    summary.torqueRelativeMagnitude(k,1) = ...
        norm(solution.torque)/(opt.radius*forceScale);
    summary.capContinuityMax(k,1) = ...
        max(report.point.continuity(validation.cap))/solution.velocityScale;
    summary.mobileContinuityMax(k,1) = ...
        max(report.point.continuity(validation.mobile))/solution.velocityScale;
    summary.capNoPenetrationMax(k,1) = ...
        max(report.point.normal(validation.cap))/solution.velocityScale;
    summary.mobileNoPenetrationMax(k,1) = ...
        max(report.point.normal(validation.mobile))/solution.velocityScale;
    summary.capTangentialMax(k,1) = ...
        max(report.point.capOuter(validation.cap))/solution.velocityScale;
    summary.mobileTractionMax(k,1) = ...
        max(report.point.mobileTraction(validation.mobile))/solution.tractionScale;
    coefficients = image_source_coefficients( ...
        solution.exteriorBasis,solution.lambda);
    summary.enhancingStokesletMaxOverForce(k,1) = ...
        max(vecnorm(coefficients{2},2,2))/forceScale;
    summary.derivativeMaxOverForce(k,1) = ...
        max(vecnorm(coefficients{3},2,2))/forceScale;
end
disp(summary);
disp(regionRows(:,{'direction','condition','region','zone', ...
    'nodeCount','minimumEdgeDistance','maximum','rms'}));
fprintf('Velocity maxima / U_*; traction maxima / (muOut*U_*/a).\n');
writetable(summary,fullfile(outputDirectory, ...
    'oct24_stagnant_cap_derivatives_summary.csv'));
writetable(regionRows,fullfile(outputDirectory, ...
    'oct24_stagnant_cap_derivatives_validation.csv'));

% Pool each condition across both cases so its two surface maps share colours.
fields = {'continuity','normal','capOuter','mobileTraction'};
masks = {true(validation.count,1),true(validation.count,1), ...
    validation.cap,validation.mobile};
residualLimits = zeros(4,2);
for condition = 1:4
    pooled = [];
    for k = 1:2
        if condition<4
            scale = solutions{k}.velocityScale;
        else
            scale = solutions{k}.tractionScale;
        end
        values = reports{k}.point.(fields{condition})(masks{condition})/scale;
        pooled = [pooled;values]; %#ok<AGROW>
    end
    positive = pooled(pooled>0);
    if isempty(positive)
        floorLog = -16;
    else
        floorLog = max(-16,floor(log10(min(positive)))-1);
    end
    residualLimits(condition,:) = [floorLog, ...
        max(floorLog+0.5,max(log10(max(pooled,10^floorLog))))];
    fprintf('%s map: zero display floor 10^(%.0f); matched limits [%.3g, %.3g].\n', ...
        fields{condition},floorLog,residualLimits(condition,:));
end
for k = 1:2
    f = plot_stagnant_cap_residuals(reports{k},validation, ...
        solutions{k},opt,'on',residualLimits,directions(k));
    exportgraphics(f,fullfile(outputDirectory,sprintf( ...
        'oct24_stagnant_cap_derivatives_residuals_%s.png', ...
        directions(k))),'Resolution',150);
end

% Use the same meridional targets, including points on both sides of the edge.
near = logspace(log10(validation.minimumEdgeDistance/opt.radius), ...
    log10(opt.edgeBandAngle),90);
theta = sort(unique([linspace(0.02,pi-0.02,180), ...
    opt.phi-near,opt.phi+near]));
theta = theta(theta>0 & theta<pi & abs(theta-opt.phi)>1e-12).';
normal = [sin(theta),zeros(numel(theta),1),cos(theta)];
profile.points = opt.centre+opt.radius*normal;
profile.normals = normal;
profile.theta = theta;
profile.cap = theta<opt.phi;
profile.mobile = theta>opt.phi;
profile.edgeDistance = opt.radius*abs(theta-opt.phi);
profile.nearEdge = profile.edgeDistance<=opt.radius*opt.edgeBandAngle;
profile.minimumEdgeDistance = min(profile.edgeDistance);
profile.count = numel(theta);
relativeTheta = zeros(profile.count,2);
for k = 1:2
    trace = stagnant_cap_validate(solutions{k},profile,opt);
    relativeTheta(:,k) = ...
        trace.point.meridionalVelocity/solutions{k}.velocityScale;
end
sOverA = theta(profile.mobile)-opt.phi;
f = figure('Name','Stagnant-cap derivative velocity','Color','w');
tiledlayout(f,1,3,'TileSpacing','compact');
ax = nexttile; hold(ax,'on');
plot(ax,theta,relativeTheta(:,1),'b-',theta,relativeTheta(:,2),'r-');
xline(ax,opt.phi,'k--');
xlabel(ax,'polar angle \theta'); ylabel(ax,'drop-relative u_\theta/U_*');
legend(ax,directions,'Location','best'); grid(ax,'on');
ax = nexttile; hold(ax,'on');
plot(ax,sOverA,relativeTheta(profile.mobile,1),'b-', ...
    sOverA,relativeTheta(profile.mobile,2),'r-');
plot(ax,0,0,'ko','MarkerFaceColor','k');
xlim(ax,[0 opt.edgeBandAngle]);
xlabel(ax,'mobile edge distance s/a'); ylabel(ax,'drop-relative u_\theta/U_*');
grid(ax,'on');
ax = nexttile; hold(ax,'on');
semilogx(ax,sOverA,relativeTheta(profile.mobile,1)./sqrt(sOverA),'b-', ...
    sOverA,relativeTheta(profile.mobile,2)./sqrt(sOverA),'r-');
xlim(ax,[min(sOverA) opt.edgeBandAngle]);
xlabel(ax,'mobile edge distance s/a');
ylabel(ax,'u_\theta/(U_*\surd(s/a))'); grid(ax,'on');
exportgraphics(f,fullfile(outputDirectory, ...
    'oct24_stagnant_cap_derivatives_velocity.png'),'Resolution',180);

% Match coefficient colour limits across direction cases, separately by side
% and by basis block (base S, enhancing S, derivative S_y).
coefficientLimits = cell(2,3);
for side = 1:2
    for block = 1:3
        pooled = [];
        for k = 1:2
            if side==1
                basis = solutions{k}.exteriorBasis;
                strength = solutions{k}.lambda;
            else
                basis = solutions{k}.interiorBasis;
                strength = solutions{k}.gamma;
            end
            coefficients = image_source_coefficients(basis,strength);
            pooled = [pooled;log10(max( ...
                vecnorm(coefficients{block},2,2)/forceScale,1e-16))]; %#ok<AGROW>
        end
        bounds = [min(pooled),max(pooled)];
        if bounds(1)==bounds(2), bounds = bounds+[-0.5 0.5]; end
        coefficientLimits{side,block} = bounds;
    end
end
for k = 1:2
    f = plot_stagnant_cap_source_strengths( ...
        solutions{k},directions(k),'on',forceScale,coefficientLimits);
    exportgraphics(f,fullfile(outputDirectory,sprintf( ...
        'oct24_stagnant_cap_derivatives_strengths_%s.png', ...
        directions(k))),'Resolution',180);
end

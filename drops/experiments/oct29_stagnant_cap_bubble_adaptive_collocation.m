%% October 29: residual-driven collocation with a bounded dense SVD
% Run after adding the repository paths, or run this file directly.
% The three conditions are normal velocity everywhere, cap tangential
% velocity, and mobile tangential traction. Normal velocity is audited on
% both regions. The target applies to PHYSICAL normalized maxima, not RMS
% errors or weighted equations. No continuous-surface certificate is claimed.
%
% Only Stokeslets are used. The uniform proxy is smaller/deeper than oct24;
% clustered edge sources remain fixed while collocation points are adapted.
% A fixed source space may be insufficient: inspect result.converged/status.
% On memory, point, iteration, or stagnation limits, the script saves the
% unsuccessful result and its independently audited errors without claiming
% that the requested tolerance was achieved.
clear; close all;
experimentDirectory = fileparts(mfilename('fullpath'));
repositoryDirectory = fileparts(fileparts(experimentDirectory));
addpath(fullfile(repositoryDirectory,'drops'), ...
    fullfile(repositoryDirectory,'images'), ...
    fullfile(repositoryDirectory,'common','dense'), ...
    fullfile(repositoryDirectory,'geometry','spheres'), ...
    fullfile(repositoryDirectory,'tools'));
outputDirectory = fullfile(experimentDirectory,'results');
if ~isfolder(outputDirectory), mkdir(outputDirectory); end
prefix = 'oct29_stagnant_cap_bubble_adaptive_collocation';

% Sources: fewer global proxies, deeper radius; retain the edge Stokeslets.
% sourceRequest is rounded UP to an available spherical design.
input = struct('radius',1,'muOut',1,'phi',pi/4, ...
    'sourceRequest',200,'innerProxyRatio',0.5, ...
    'collocationRatio',2,'svdTolerance',1e-12, ...
    'useColumnScaling',true,'useAreaWeights',false, ...
    'useConditionCountScaling',true,'conditionWeights',[1 1 1], ...
    'gravity',[0 0 -1],'densityDifference',1, ...
    'n_level',10,'ringLevels',20,'innerSourceStartDistance',0.35, ...
    'sourceClustering',"tapered",'sourceClusterSigma',3, ...
    'n_az_source',64,'n_az_colloc',40, ...
    'collocAngularExtent',0.05,'collocClustering',"geometric", ...
    'collocClusterRatio',0.65,'useSourceRefinement',false, ...
    'refinementFamilies',"S",'derivative_direction',"none",'batchSize',128);

% HARD SIZE LIMITS are checked before allocating/assembling the dense system.
% maxMemoryGB uses a conservative estimate including assembly, copies, SVD
% factors and workspace; actual MATLAB/library overhead can differ.
controls = struct('tolerance',1e-2,'maxIterations',15, ...
    'initialCollocationPoints',1200,'maxCollocationPoints',3000, ...
    'maxNewPointsPerIteration',192,'maxSvdRows',9000, ...
    'selectionMode',"rings",'ringAzimuthCount',64, ...
    'maxSvdColumns',3000,'maxMemoryGB',2, ...
    'validationBaseRequest',10000,'edgeAuditDistanceOverA',1e-10, ...
    'auditSourceLevels',3, ...
    'useResidualWeights',true,'balanceConditions',true, ...
    'weightDamping',0.5,'maxPointWeight',100,'maxConditionWeight',30, ...
    'stagnationIterations',4,'minimumImprovement',0.01,'verbose',true);
% Set useResidualWeights=false / balanceConditions=false to compare weighting.
% conditionWeights order: [normal, cap tangential velocity, mobile traction].
% Increasing a weight emphasizes that condition; it never relaxes its target.
% Area weighting targets a surface L2 norm and is off for this maximum-error goal.
% selectionMode="rings" adds complete uniform rings at high-error latitudes.
% ringAzimuthCount sets points around EVERY seed/refinement ring; increase it
% to check along-edge resolution. 192/64 permits up to three rings per step.
% Rings are ranked using the largest residual over the sampled azimuths.
% Set selectionMode="points" to restore individual-point selection.
% Global spherical-design seed nodes are retained in both modes.
% Fresh phase-shifted audits prevent success from being based on reused targets.

result = bubble_adaptive_collocation(input,controls);
save(fullfile(outputDirectory,[prefix,'_data.mat']),'result');
if width(result.history)>0
    writetable(result.history,fullfile(outputDirectory,[prefix,'_history.csv']));
end
fprintf('\nFinal status: %s; converged=%d. %s\n', ...
    result.status,result.converged,result.message);
if ~isempty(result.solution)
    solution = result.solution;
    opt = result.opt;
    [geometry3D,geometryMeridional] = bubble_plot_geometry(solution.grid,opt,'on');
    residualFigure = bubble_plot_residuals( ...
        result.report,result.validation,solution,opt,'on');
    collocationFigure = bubble_plot_collocation_residuals(solution,opt,'on');
    distanceFigure = bubble_plot_residuals_distance( ...
        result.report,result.validation,solution,opt,'on');
    [strength3D,strengthMeridional] = bubble_plot_strengths(solution,opt,'on');
    figures = [geometry3D,geometryMeridional,residualFigure, ...
        collocationFigure,distanceFigure,strength3D,strengthMeridional];
    suffixes = {'geometry_3d','geometry_meridional','residuals', ...
        'residuals_collocation','residuals_distance', ...
        'strengths_3d','strengths_meridional'};
    for k = 1:numel(figures)
        exportgraphics(figures(k),fullfile(outputDirectory, ...
            [prefix,'_',suffixes{k},'.png']),'Resolution',180);
    end
    maxima = vertcat(result.auditReports{1}.maxima,result.auditReports{2}.maxima);
    summary = array2table(maxima,'VariableNames', ...
        {'capNormal','mobileNormal','capVelocity','mobileTraction'});
    summary.audit = (1:2).';
    summary.converged = repmat(result.converged,2,1);
    summary.status = repmat(result.status,2,1);
    writetable(summary,fullfile(outputDirectory,[prefix,'_audits.csv']));
end

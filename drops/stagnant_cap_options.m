function opt = stagnant_cap_options(user)
%STAGNANT_CAP_OPTIONS Complete controls for one axis-aligned stagnant-cap drop.
if nargin == 0
    self_test();
    return
end
if isempty(user), user = struct(); end
assert(isstruct(user) && isscalar(user));
defaults = struct('radius',1,'centre',[0 0 0], ...
    'muOut',1,'muIn',2,'phi',pi/2,'innerProxyRatio',0.4, ...
    'outerProxyRatio',2,'sourceRequest',100,'collocationRatio',1.5, ...
    'ringLevels',4,'ringAzimuthCount',[], ...
    'useExtraCollocation',true, ...
    'edgeBandAngle',[],'svdTolerance',1e-12,'batchSize',256, ...
    'validationBaseRequest',0,'validationMultiplier',5, ...
    'plotThetaCount',120,'plotAzimuthCount',80, ...
    'gravity',[0 0 -1],'densityDifference',1, ...
    'completionScale',[], ...
    'n_level',5,'colloc_factor',2, ...
    'sourceClusterRatio',0.7, ...
    'innerSourceStartDistance',[], ...
    'outerSourceStartDistance',[], ...
    'n_az_source',64,'n_az_colloc',64, ...
    'collocAngularExtent',[],'collocClusterRatio',0.8, ...
    'refinementFamilies',"S",'use_orth_dir_images',false, ...
    'derivative_direction',"none");
opt = defaults;
names = fieldnames(user);
for k = 1:numel(names)
    assert(isfield(defaults,names{k}), ...
        'stagnant_cap_options:UnknownOption','Unknown option %s.',names{k});
    opt.(names{k}) = user.(names{k});
end
validateattributes(opt.radius,{'numeric'},{'real','finite','scalar','positive'});
validateattributes(opt.muOut,{'numeric'},{'real','finite','scalar','positive'});
validateattributes(opt.muIn,{'numeric'},{'real','finite','scalar','positive'});
validateattributes(opt.phi,{'numeric'},{'real','finite','scalar','>=',0,'<=',pi});
assert(isequal(size(opt.centre),[1 3]) && all(isfinite(opt.centre)));
assert(isequal(size(opt.gravity),[1 3]) && all(isfinite(opt.gravity)) && ...
    opt.gravity(1)==0 && opt.gravity(2)==0 && opt.gravity(3)~=0);
validateattributes(opt.densityDifference,{'numeric'}, ...
    {'real','finite','scalar'});
assert(opt.innerProxyRatio>0 && opt.innerProxyRatio<1 && ...
    opt.outerProxyRatio>1);
assert(opt.sourceRequest>=6 && opt.sourceRequest==round(opt.sourceRequest));
assert(opt.collocationRatio>1);
assert(opt.ringLevels>=0 && opt.ringLevels==round(opt.ringLevels));
assert(islogical(opt.useExtraCollocation) && ...
    isscalar(opt.useExtraCollocation), ...
    'useExtraCollocation must be true or false.');
if ~isempty(opt.ringAzimuthCount)
    assert(opt.ringAzimuthCount>=4 && ...
        opt.ringAzimuthCount==round(opt.ringAzimuthCount));
end
if isempty(opt.edgeBandAngle)
    opt.edgeBandAngle = min([0.2,opt.phi/4,(pi-opt.phi)/4]);
end
assert(opt.edgeBandAngle>=0 && ...
    opt.edgeBandAngle<=min(opt.phi,pi-opt.phi));
assert(opt.svdTolerance>0 && opt.svdTolerance<1);
assert(opt.batchSize>=1 && opt.batchSize==round(opt.batchSize));
assert(opt.validationBaseRequest>=0 && ...
    opt.validationBaseRequest==round(opt.validationBaseRequest));
assert(opt.validationMultiplier>=5);
assert(opt.plotThetaCount>=20 && opt.plotAzimuthCount>=12);
if isempty(opt.completionScale)
    opt.completionScale = 1/(6*pi*opt.muOut*opt.radius);
end
assert(opt.completionScale>0 && isfinite(opt.completionScale));
validateattributes(opt.n_level,{'numeric'}, ...
    {'scalar','integer','nonnegative'});
validateattributes(opt.colloc_factor,{'numeric'}, ...
    {'scalar','real','finite','>=',2});
validateattributes(opt.sourceClusterRatio,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1});
if isempty(opt.innerSourceStartDistance)
    opt.innerSourceStartDistance = 0.45*opt.radius;
end
if isempty(opt.outerSourceStartDistance)
    opt.outerSourceStartDistance = 0.45*opt.radius;
end
validateattributes(opt.innerSourceStartDistance,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<',opt.radius});
validateattributes(opt.outerSourceStartDistance,{'numeric'}, ...
    {'scalar','real','finite','>',0});
validateattributes(opt.n_az_source,{'numeric'}, ...
    {'scalar','integer','>=',4});
validateattributes(opt.n_az_colloc,{'numeric'}, ...
    {'scalar','integer','>=',4});
if isempty(opt.collocAngularExtent)
    opt.collocAngularExtent = opt.edgeBandAngle;
end
validateattributes(opt.collocAngularExtent,{'numeric'}, ...
    {'scalar','real','finite','>=',0});
validateattributes(opt.collocClusterRatio,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1});
assert(islogical(opt.use_orth_dir_images) && ...
    isscalar(opt.use_orth_dir_images));
opt.refinementFamilies = image_family_list(opt.refinementFamilies);
opt.derivative_direction = string(opt.derivative_direction);
assert(isscalar(opt.derivative_direction) && ...
    ismember(opt.derivative_direction,["none","radial","cone_normal"]), ...
    'derivative_direction must be none, radial, or cone_normal.');
end

function self_test()
%SELF_TEST Check dimensional defaults and rejection of invalid geometry.
o = stagnant_cap_options(struct());
assert(abs(o.completionScale-1/(6*pi))<eps);
assert(abs(o.edgeBandAngle-0.2)<eps);
assert(o.useExtraCollocation);
assert(o.n_level==5 && o.colloc_factor==2 && ...
    o.n_az_source==64 && o.n_az_colloc==64);
assert(abs(o.innerSourceStartDistance-0.45)<eps && ...
    abs(o.outerSourceStartDistance-0.45)<eps);
p = stagnant_cap_options(struct('radius',2,'muOut',3,'phi',pi/3));
assert(abs(p.completionScale-1/(36*pi))<eps);
assert(p.innerProxyRatio<1 && p.outerProxyRatio>1);
q = stagnant_cap_options(struct('useExtraCollocation',false));
assert(~q.useExtraCollocation);
r = stagnant_cap_options(struct('refinementFamilies',"SR"));
assert(isequal(r.refinementFamilies,["S","R"]));
explicit = stagnant_cap_options(struct( ...
    'refinementFamilies',"ST_tT_nT_n2"));
assert(isequal(explicit.refinementFamilies, ...
    ["S","T_t","T_n","T_n2"]));
assert(isequal(stagnant_cap_options(explicit).refinementFamilies, ...
    explicit.refinementFamilies));
assert(o.derivative_direction=="none");
assert(stagnant_cap_options(struct( ...
    'derivative_direction',"cone_normal")).derivative_direction=="cone_normal");
try
    stagnant_cap_options(struct('phi',pi+0.01));
    error('stagnant_cap_options:SelfTest','Invalid angle was accepted.');
catch ME
    assert(~strcmp(ME.identifier,'stagnant_cap_options:SelfTest'));
end
fprintf('stagnant_cap_options self-test passed.\n');
end

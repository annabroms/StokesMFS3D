function [figure3D,figureClose] = plot_stagnant_cap_geometry(geometry,opt,visibility)
%PLOT_STAGNANT_CAP_GEOMETRY Show actual proxies, interface, edge and nodes.
if nargin == 0
    self_test();
    return
end
if nargin<3, visibility = 'on'; end
opt = stagnant_cap_options(opt);
a = opt.radius;
c = opt.centre;
[sx,sy,sz] = sphere(64);
capSurface = acos(max(-1,min(1,sz)))<opt.phi;
figure3D = figure('Name','Stagnant-cap discretization', ...
    'Color','w','Visible',visibility);
ax = axes(figure3D);
hold(ax,'on');
inner = surf(ax,c(1)+a*opt.innerProxyRatio*sx, ...
    c(2)+a*opt.innerProxyRatio*sy,c(3)+a*opt.innerProxyRatio*sz, ...
    'FaceColor',[0.25 0.45 0.9],'FaceAlpha',0.08,'EdgeColor','none');
outer = surf(ax,c(1)+a*opt.outerProxyRatio*sx, ...
    c(2)+a*opt.outerProxyRatio*sy,c(3)+a*opt.outerProxyRatio*sz, ...
    'FaceColor',[0.95 0.48 0.12],'FaceAlpha',0.04,'EdgeColor','none');
xc = c(1)+a*sx; yc = c(2)+a*sy; zc = c(3)+a*sz;
xm = xc; ym = yc; zm = zc;
xc(~capSurface)=NaN; yc(~capSurface)=NaN; zc(~capSurface)=NaN;
xm(capSurface)=NaN; ym(capSurface)=NaN; zm(capSurface)=NaN;
capHandle = surf(ax,xc,yc,zc,'FaceColor',[0.66 0.38 0.73], ...
    'FaceAlpha',0.34,'EdgeColor','none');
mobileHandle = surf(ax,xm,ym,zm,'FaceColor',[0.17 0.72 0.67], ...
    'FaceAlpha',0.25,'EdgeColor','none');
psi = linspace(0,2*pi,400);
edge = c+a*[sin(opt.phi)*cos(psi(:)), ...
    sin(opt.phi)*sin(psi(:)),cos(opt.phi)*ones(numel(psi),1)];
edgeHandle = plot3(ax,edge(:,1),edge(:,2),edge(:,3), ...
    'k-','LineWidth',2.2);
yin = geometry.innerSources; yex = geometry.outerSources;
innerNodes = scatter3(ax,yin(:,1),yin(:,2),yin(:,3), ...
    25,[0.04 0.25 0.85],'o','filled');
outerNodes = scatter3(ax,yex(:,1),yex(:,2),yex(:,3), ...
    27,[0.9 0.34 0.04],'^','filled');
baseCap = geometry.points(geometry.baseCollocation & geometry.cap,:);
baseMobile = geometry.points(geometry.baseCollocation & geometry.mobile,:);
ringCap = geometry.points(geometry.ringCollocation & geometry.cap,:);
ringMobile = geometry.points(geometry.ringCollocation & geometry.mobile,:);
capNodes = scatter3(ax,baseCap(:,1),baseCap(:,2),baseCap(:,3), ...
    18,[0.55 0.04 0.65],'s');
mobileNodes = scatter3(ax,baseMobile(:,1),baseMobile(:,2),baseMobile(:,3), ...
    14,[0.02 0.52 0.42],'o');
capRingNodes = scatter3(ax,ringCap(:,1),ringCap(:,2),ringCap(:,3), ...
    25,[0.8 0.07 0.48],'d','filled');
mobileRingNodes = scatter3(ax,ringMobile(:,1),ringMobile(:,2),ringMobile(:,3), ...
    23,[0.0 0.68 0.32],'^','filled');
axis(ax,'equal'); set(ax,'XGrid','on','YGrid','on','ZGrid','on');
view(ax,35,22);
xlabel(ax,'x'); ylabel(ax,'y'); zlabel(ax,'z');
title(ax,sprintf('N=%d, M=%d; cap angle %.3g rad', ...
    geometry.N,geometry.collocationCount,opt.phi));
legend(ax,[capHandle,mobileHandle,edgeHandle,inner,outer, ...
    innerNodes,outerNodes,capNodes,mobileNodes, ...
    capRingNodes,mobileRingNodes], ...
    {'stagnant cap','mobile interface','cap edge','inner proxy', ...
    'outer proxy','exterior-field sources','interior-field sources', ...
    'base cap collocation','base mobile collocation', ...
    'added cap rings','added mobile rings'},'Location','eastoutside');

figureClose = figure('Name','Cap-edge collocation close-up', ...
    'Color','w','Visible',visibility);
ax = axes(figureClose);
hold(ax,'on');
band = max(geometry.bandAngle,0.08);
thetaArc = linspace(max(0,opt.phi-1.2*band), ...
    min(pi,opt.phi+1.2*band),300);
plot(ax,c(1)+a*sin(thetaArc),c(3)+a*cos(thetaArc), ...
    'k-','LineWidth',1.2);
plot(ax,c(1)+a*sin(opt.phi),c(3)+a*cos(opt.phi), ...
    'kp','MarkerSize',13,'MarkerFaceColor','k');
near = abs(geometry.theta-opt.phi)<=1.15*band;
baseCapNear = near & geometry.baseCollocation & geometry.cap;
baseMobileNear = near & geometry.baseCollocation & geometry.mobile;
ringCapNear = near & geometry.ringCollocation & geometry.cap;
ringMobileNear = near & geometry.ringCollocation & geometry.mobile;
scatter(ax,c(1)+a*sin(geometry.theta(baseCapNear)), ...
    c(3)+a*cos(geometry.theta(baseCapNear)),42,[0.55 0.04 0.65],'s');
scatter(ax,c(1)+a*sin(geometry.theta(baseMobileNear)), ...
    c(3)+a*cos(geometry.theta(baseMobileNear)),38,[0.02 0.52 0.42],'o');
scatter(ax,c(1)+a*sin(geometry.theta(ringCapNear)), ...
    c(3)+a*cos(geometry.theta(ringCapNear)),32,[0.8 0.07 0.48], ...
    'd','filled');
scatter(ax,c(1)+a*sin(geometry.theta(ringMobileNear)), ...
    c(3)+a*cos(geometry.theta(ringMobileNear)),30,[0.0 0.68 0.32], ...
    '^','filled');
axis(ax,'equal'); set(ax,'XGrid','on','YGrid','on');
xlabel(ax,'meridional radius'); ylabel(ax,'z');
title(ax,sprintf('Base nodes retained + rings added; nearest offset %.4g rad', ...
    min(geometry.edgeDistance)/a));
legend(ax,{'physical interface','cap-edge circle', ...
    'base cap','base mobile','added cap rings','added mobile rings'}, ...
    'Location','best');
end

function self_test()
%SELF_TEST Verify plotted point counts and edge curve for an actual geometry.
o = stagnant_cap_options(struct('sourceRequest',50,'ringLevels',3));
g = stagnant_cap_geometry(o);
[f1,f2] = plot_stagnant_cap_geometry(g,o,'off');
assert(isgraphics(f1) && isgraphics(f2));
scatters = findall(f1,'Type','Scatter');
assert(numel(scatters)==6);
assert(sum(arrayfun(@(h) numel(h.XData),scatters))== ...
    2*g.N+g.collocationCount);
assert(numel(findall(f2,'Type','Scatter'))==4);
assert(nnz(g.ringCollocation)==2*o.ringLevels*g.ringAzimuthCount);
assert(numel(findall(f1,'Type','Surface'))==4);
close(f1); close(f2);
fprintf('plot_stagnant_cap_geometry self-test passed.\n');
end

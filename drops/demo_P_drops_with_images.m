%DEMO_P_DROPS_WITH_IMAGES Configurable P-body image solve.
root = fileparts(fileparts(mfilename('fullpath')));
addpath(genpath(root));
runDenseSVD = false;             % Full-system reference, available for P=2.
% imageFamilies tokens: S Stokeslet, R rotlet, D potential dipole, T legacy
% stresslet, T_t line-parallel, T_n first transverse, T_n2 second transverse
% stresslet, Q_s trace-free axial Stokeslet quadrupole. T excludes T_*.
P = 2;                         % Change this count without changing indexing.
if runDenseSVD && P~=2
    error('demo_P_drops_with_images:DenseTwoOnly', ...
        'The full-system dense SVD is available only for P=2.');
end
gap = 0.1;
a = ones(P,1);
q = [(0:P-1).'*(2+gap),zeros(P,2)];
S1 = ones(P,1);
e = repmat([1 0 0],P,1);
opt = struct('N',700,'collocationRatio',1.2,'nearThreshold',0.15, ...
    'imageFamilies',"SRDT_nT_t",'mirror_ext',true,'useImages',true, ...
    'use_orth_dir_images',false, ...
    'proxyRadius',0.63,'outerProxyRatio',2, ...
    'outerImageOffsetFraction',0.01, ...
    'interiorViscosity',2,'solverMode',"oneBody", ...
    'svdCutoff',1e-12,'gmresTolerance',1e-9,'maxIterations',300, ...
    'batchSize',128,'validationCount',1000,'validationGapCount',401, ...
    'plot_grid',1);
[U,lambda,gamma,grid,info] = solve_drops_with_images(q,a,S1,e,opt);
[err,~,points,normals] = drop_image_validate_surface_conditions( ...
    grid,lambda,gamma,U,S1,e,info.options);
fprintf('P=%d, A size %d x %d, GMRES iterations %d\n', ...
    P,info.systemSize,info.iterations);
fprintf('original scaled residual %.3e, preconditioned residual %.3e\n', ...
    info.originalResidual,info.regularizedResidual);
fprintf('setup %.3fs (SVD %.3fs), one matvec %.3fs, solve %.3fs\n', ...
    info.setupTime,info.factorizationTime,info.matvecTime,info.solveTime);
disp(table((1:P).',U(:,1),U(:,2),U(:,3), ...
    err(:,1),err(:,2),err(:,3), ...
    'VariableNames',{'Body','Ux','Uy','Uz','Continuity','Normal','Traction'}));
fprintf('Independent validation nodes per body: ');
fprintf('%d ',cellfun(@(x) size(x,1),points)); fprintf('\n');
drop_image_plot_source_strengths(grid,lambda,gamma, ...
    sprintf('%d drops (iterative)',P));

% The optional reference uses the same geometry and validation nodes.
if runDenseSVD
    denseOpt = opt;
    denseOpt.solverMode = "denseSVD";
    [denseU,denseLambda,denseGamma,~,denseInfo] = ...
        solve_drops_with_images(q,a,S1,e,denseOpt);
    denseError = drop_image_validate_surface_conditions( ...
        grid,denseLambda,denseGamma,denseU,S1,e, ...
        denseInfo.options,points,normals);
    fprintf('dense SVD rank %d, original scaled residual %.3e\n', ...
        denseInfo.retainedRanks,denseInfo.originalResidual);
    fprintf('relative translation difference %.3e\n', ...
        norm(U-denseU,'fro')/max(norm(denseU,'fro'),eps));
    disp(table((1:P).',denseU(:,1),denseU(:,2),denseU(:,3), ...
        denseError(:,1),denseError(:,2),denseError(:,3), ...
        'VariableNames',{'Body','Ux','Uy','Uz', ...
        'Continuity','Normal','Traction'}));
end
